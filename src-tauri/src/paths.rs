use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

/// Default data folder and the home of the custom-location pointer file. The
/// value never changes even when data moves, so DevKu always knows where
/// to read the pointer from.
pub fn default_home() -> PathBuf {
    #[cfg(windows)]
    {
        if let Ok(appdata) = std::env::var("APPDATA") {
            return PathBuf::from(appdata).join("DevKu");
        }
    }

    #[cfg(not(windows))]
    {
        if let Ok(xdg) = std::env::var("XDG_DATA_HOME") {
            return PathBuf::from(xdg).join("devku");
        }
        if let Ok(home) = std::env::var("HOME") {
            return PathBuf::from(home).join(".local/share/devku");
        }
    }

    PathBuf::from(".devku")
}

/// All DevKu state lives under one root so it can be moved or deleted as a whole.
/// `DEVKU_HOME` wins, then the pointer from Settings, then the default folder.
pub fn home() -> PathBuf {
    let default = default_home();
    crate::location::resolve(&default, crate::location::env_home()).0
}

/// User home folder, the basis for the default workspace location. Workspace
/// deliberately stays out of the data folder: projects are content, not app state.
pub fn user_home() -> Option<PathBuf> {
    #[cfg(windows)]
    {
        std::env::var("USERPROFILE")
            .ok()
            .filter(|value| !value.is_empty())
            .map(PathBuf::from)
    }

    #[cfg(not(windows))]
    {
        std::env::var("HOME")
            .ok()
            .filter(|value| !value.is_empty())
            .map(PathBuf::from)
    }
}

/// Default location of the `sites/` folder. Used by the wizard and the open workspace button
/// until the user picks one.
pub fn default_workspace() -> PathBuf {
    match user_home() {
        Some(home) => home.join("DevKu").join("sites"),
        None => default_home().join("sites"),
    }
}

#[derive(Clone, Debug)]
pub struct Paths {
    pub root: PathBuf,
}

impl Paths {
    pub fn resolve() -> Self {
        Self { root: home() }
    }

    pub fn config_file(&self) -> PathBuf {
        self.root.join("config.json")
    }

    pub fn engines(&self) -> PathBuf {
        self.root.join("engines")
    }

    pub fn php_dir(&self, version: &str) -> PathBuf {
        self.engines().join("php").join(version)
    }

    pub fn caddy_binary(&self) -> PathBuf {
        self.engines()
            .join("caddy")
            .join(if cfg!(windows) { "caddy.exe" } else { "caddy" })
    }

    pub fn caddy_dir(&self) -> PathBuf {
        self.engines().join("caddy")
    }

    pub fn apache_dir(&self) -> PathBuf {
        self.engines().join("apache")
    }

    /// One Apache version installed by DevKu, for example `2.4.69-261002`.
    pub fn apache_version_dir(&self, version: &str) -> PathBuf {
        self.apache_dir().join(version)
    }

    pub fn mariadb_dir(&self) -> PathBuf {
        self.engines().join("mariadb")
    }

    /// `bin/` must stay next to `server.dll`: the mysqld stub loads the server
    /// from the same folder.
    pub fn mariadb_bin(&self) -> PathBuf {
        self.mariadb_dir().join("bin")
    }

    /// User data is deliberately separate from `engines/`, so reinstalling binaries
    /// does not touch the database.
    pub fn mariadb_data(&self) -> PathBuf {
        self.root.join("databases").join("mariadb")
    }

    pub fn mariadb_runtime(&self) -> PathBuf {
        self.runtime().join("mariadb")
    }

    pub fn mariadb_config(&self) -> PathBuf {
        self.mariadb_runtime().join("my.ini")
    }

    /// The root password is stored outside `config.json` so it is not exported along with it.
    pub fn mariadb_password(&self) -> PathBuf {
        self.mariadb_runtime().join("root.pass")
    }

    pub fn backups(&self) -> PathBuf {
        self.root.join("backups")
    }

    pub fn runtime(&self) -> PathBuf {
        self.root.join("runtime")
    }

    pub fn logs(&self) -> PathBuf {
        self.runtime().join("logs")
    }

    /// Temporary download files (PHP/Caddy zips) before installation.
    pub fn downloads(&self) -> PathBuf {
        self.runtime().join("downloads")
    }

    pub fn caddyfile(&self) -> PathBuf {
        self.runtime().join("Caddyfile")
    }

    /// Apache configuration generated by DevKu, separate from the
    /// Apache installation folder so it does not overwrite the user's conf.
    pub fn apache_runtime(&self) -> PathBuf {
        self.runtime().join("apache")
    }

    pub fn apache_config(&self) -> PathBuf {
        self.apache_runtime().join("httpd.conf")
    }

    pub fn dashboard_dir(&self) -> PathBuf {
        self.runtime().join("dashboard")
    }

    /// Binaries DevKu provides itself when the machine lacks its own version.
    pub fn bundled_binary(&self, name: &str) -> PathBuf {
        let file = if cfg!(windows) {
            format!("{name}.exe")
        } else {
            name.to_string()
        };
        self.engines().join(name).join(file)
    }

    pub fn ensure(&self) -> Result<()> {
        for dir in [
            self.root.clone(),
            self.engines(),
            self.runtime(),
            self.logs(),
        ] {
            std::fs::create_dir_all(&dir)
                .with_context(|| format!("gagal membuat {}", dir.display()))?;
        }
        Ok(())
    }
}

/// Writes a file via temp + rename so config is never half written.
pub fn write_atomic(path: &Path, contents: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let tmp = path.with_extension("tmp");
    std::fs::write(&tmp, contents).with_context(|| format!("gagal menulis {}", tmp.display()))?;
    std::fs::rename(&tmp, path).with_context(|| format!("gagal memindahkan {}", path.display()))?;
    Ok(())
}
